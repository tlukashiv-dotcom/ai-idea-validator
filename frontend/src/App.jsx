import { useEffect, useState } from 'react'
import { validateIdea, DEMO_MODE } from './api'
import { EXAMPLES } from './examples'
import {
  ScoreRing, Card, Competitors, Swot, LeanCanvas, Risks, NextSteps, Sources,
} from './components'

const REPO_URL = 'https://github.com/tlukashiv-dotcom/ai-idea-validator'

const LOADING_STEPS = [
  'Searching the web for competitors…',
  'Analyzing the market…',
  'Building SWOT and Lean Canvas…',
  'Assessing risks…',
]

function Loading() {
  const [step, setStep] = useState(0)
  useEffect(() => {
    const t = setInterval(() => setStep((s) => Math.min(s + 1, LOADING_STEPS.length - 1)), 4000)
    return () => clearInterval(t)
  }, [])
  return (
    <div className="loading" role="status">
      <div className="spinner" />
      <p>{LOADING_STEPS[step]}</p>
    </div>
  )
}

function DemoBanner() {
  return (
    <div className="demo-banner">
      <strong>Demo version.</strong> These are real reports generated by the AI assistant —
      pick one below. Live analysis of any idea runs on the n8n backend; see how to run it in
      the <a href={REPO_URL} target="_blank" rel="noreferrer">GitHub repository</a>.
    </div>
  )
}

export default function App() {
  const [idea, setIdea] = useState('')
  const [market, setMarket] = useState('')
  const [status, setStatus] = useState('idle') // idle | loading | done | error
  const [result, setResult] = useState(null)
  const [error, setError] = useState('')

  function showExample(ex) {
    setIdea(ex.idea)
    setMarket(ex.market)
    if (DEMO_MODE) {
      setError('')
      setResult(ex.report)
      setStatus('done')
    }
  }

  async function handleSubmit(e) {
    e.preventDefault()
    if (DEMO_MODE) {
      const match = EXAMPLES.find((ex) => ex.idea === idea.trim())
      if (match) return showExample(match)
      setError('The demo only includes the sample reports above. To validate your own idea, run the project locally — see the instructions on GitHub.')
      setStatus('error')
      return
    }
    if (idea.trim().length < 10) {
      setError('Please describe your idea in more detail (at least 10 characters).')
      setStatus('error')
      return
    }
    setStatus('loading')
    setError('')
    setResult(null)
    try {
      const data = await validateIdea({ idea: idea.trim(), market: market.trim() })
      setResult(data)
      setStatus('done')
    } catch (err) {
      setError(err.message)
      setStatus('error')
    }
  }

  return (
    <div className="app">
      <header className="hero">
        <div className="hero__tag">AI Business Idea Validator</div>
        <h1>Validate your business idea in 30 seconds</h1>
        <p>AI finds real competitors on the web, builds a SWOT analysis and Lean Canvas, and scores your idea's risks and viability.</p>
      </header>

      {DEMO_MODE && <DemoBanner />}

      <form className="form card" onSubmit={handleSubmit}>
        <label>
          Your idea
          <textarea
            value={idea}
            onChange={(e) => setIdea(e.target.value)}
            placeholder="e.g. a fresh-coffee subscription for offices with automatic restocking"
            rows={3}
          />
        </label>
        <label>
          Target market
          <input value={market} onChange={(e) => setMarket(e.target.value)} placeholder="Country or city" />
        </label>
        <div className="form__examples">
          <span>{DEMO_MODE ? 'Sample reports:' : 'Examples:'}</span>
          {EXAMPLES.map((ex) => (
            <button type="button" key={ex.id} className="chip" onClick={() => showExample(ex)}>
              {ex.idea} · {ex.market}
            </button>
          ))}
        </div>
        <button className="primary" disabled={status === 'loading'}>
          {status === 'loading' ? 'Analyzing…' : 'Validate idea'}
        </button>
      </form>

      {status === 'loading' && <Loading />}
      {status === 'error' && <div className="error">{error}</div>}

      {status === 'done' && result && (
        <main className="report" key={idea}>
          <Card className="summary">
            <ScoreRing score={result.score} verdict={result.verdict} />
            <div>
              <h2 className="card__title">Summary</h2>
              <p>{result.summary}</p>
            </div>
          </Card>
          <Competitors items={result.competitors} />
          <Swot swot={result.swot} />
          <LeanCanvas canvas={result.lean_canvas} />
          <div className="two-col">
            <Risks items={result.risks} />
            <NextSteps items={result.next_steps} />
          </div>
          <Sources items={result.sources} />
        </main>
      )}

      <footer className="footer">
        Built with n8n · Gemini · Tavily · React ·{' '}
        <a href={REPO_URL} target="_blank" rel="noreferrer">GitHub</a>
      </footer>
    </div>
  )
}
